"""Generate display-name compatibility data from the original deck builder.

Matches official image URLs, not guessed names or expansion ID numbering.
Only card display names and this app's IDs are retained in the deployed data.
"""
import json
from pathlib import Path
import re
import unicodedata
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
REPOSITORY = 'sweetpotato/ijinden-deck-builder'


def read_json(url):
    request = urllib.request.Request(url, headers={'User-Agent': 'ijinden-deckbook-compatibility-builder'})
    with urllib.request.urlopen(request, timeout=30) as response:
        return json.load(response)


def build():
    revision = read_json('https://api.github.com/repos/' + REPOSITORY + '/commits/main')['sha']
    source_path = '/src/commons/cards.json'
    source = read_json('https://raw.githubusercontent.com/' + REPOSITORY + '/' + revision + source_path)
    catalog_text = (ROOT / 'app/ijinden-cards.ts').read_text(encoding='utf-8')
    catalog = json.loads(re.search(r'export const ijindenCards: IjindenCard\[\] = (\[.*\]);', catalog_text, re.S)[1])
    by_image = {card['imageUrl']: card['id'] for card in catalog}
    entries = []
    seen = set()
    for card in source:
        key = re.sub(r'\s+', '', unicodedata.normalize('NFKC', card['displayName']))
        if key in seen:
            raise ValueError('Ambiguous original display name: ' + key)
        seen.add(key)
        if card['imageUrl'] not in by_image:
            raise ValueError('Update local card catalog first: ' + card['id'])
        entries.append([key, by_image[card['imageUrl']]])
    output = '// Generated by scripts/build-legacy-text-map.py; do not hand-edit.\n'
    output += '// Original display names: https://github.com/' + REPOSITORY + '/blob/' + revision + source_path + '\n'
    output += '// Card identity is verified against the official image URLs in both catalogs.\n'
    output += 'export const legacyDeckTextNames: ReadonlyMap<string, string> = new Map(\n'
    output += json.dumps(entries, ensure_ascii=False, indent=2) + '\n);\n'
    (ROOT / 'data/legacy-deck-text-names.ts').write_text(output, encoding='utf-8')
    print(f'Wrote {len(entries)} display-name mappings from {revision}.')


if __name__ == '__main__':
    build()
